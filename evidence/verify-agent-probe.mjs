import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {FixtureActivityData,FIXTURE_DIGESTS,FIXTURE_WALLET} from '../app/activity-fixtures.ts';
import {report,csv} from '../app/activity.ts';
const run=JSON.parse(readFileSync(new URL('./agent-model-probe-2026-11-06/run.json',import.meta.url),'utf8'));
assert.equal(run.data,'synthetic-fixtures');assert.equal(run.memory,'local');
assert.equal(run.tatumCalls,0);assert.equal(run.walrusCalls,0);assert.equal(run.additionalSpendUSD,0);
assert.equal(run.attempts.length,2);
const [failed,completed]=run.attempts;
assert.equal(failed.summary.status,'STOPPED');assert.equal(failed.summary.reason,'TURN_TIMEOUT');
assert.ok(failed.trace.some(t=>t.kind==='native-tool-approval'&&t.requestId===0));
assert.equal(completed.summary.status,'COMPLETED');
assert.equal(run.attempts.flatMap(a=>a.trace).filter(t=>t.kind==='user').length,run.totalUserTurnsStarted);
assert.equal(run.totalUserTurnsStarted,4);assert.equal(completed.summary.turns.length,3);
const calls=completed.trace.filter(t=>t.kind==='tool');
assert.deepEqual(calls.map(t=>t.tool),['prepare_report','verify_gas_payer','export_report']);
assert.ok(calls.every(t=>t.status==='completed'&&!t.error&&!t.result?.isError));
const decode=t=>JSON.parse(t.result.content.find(c=>c.type==='text').text);
const prepared=decode(calls[0]),verified=decode(calls[1]),exported=decode(calls[2]);
assert.equal(prepared.mode,'offline-agent-fixture');assert.deepEqual(prepared.experience,[]);
assert.equal(verified.verdict,'pass');assert.equal(verified.observed,FIXTURE_WALLET);assert.equal(verified.memory,null);
assert.equal(calls[2].arguments.reportId,prepared.reportId);
const transactions=await new FixtureActivityData('mainnet').transactions([FIXTURE_DIGESTS[0]]);
assert.equal(exported.csv,csv(report(transactions,FIXTURE_WALLET,[],prepared.asOf)));
assert.equal(completed.summary.turns[2].tools,0);
assert.ok(run.limits.length>=4);
console.log('Recorded model probe verified offline: one stopped attempt, three completed turns, exact fixture CSV, no memory-benefit claim.');
