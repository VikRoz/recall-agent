import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {validateExperienceRows} from '../app/agent-experience.ts';
import {toolSchemaHash} from '../app/agent-tool-observer.mjs';
import {assessFirstLookup,assessMemoryPair,artifactReferenceMatches} from '../app/agent-comparison-assess.mjs';
const folder=new URL('./memory-comparison-2026-11-06/',import.meta.url);
const read=name=>JSON.parse(readFileSync(new URL(name,folder),'utf8'));
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const run=read('run.json'),prep=read('preparation.json'),catalog=read('catalog.json').tool,freeze=read('freeze.json');
assert.equal(run.tatumCalls,0);assert.equal(run.walrusCalls,0);assert.equal(run.additionalSpendUSD,0);assert.equal(run.totalUserTurnsStarted,3);
assert.equal(run.frozenFilesUnchangedBeforeAndAfter,true);
assert.equal(prep.preparation,'historical-native-requests-replayed-through-current-sdk');
assert.equal(prep.sourceArtifactSha256,hash(readFileSync(new URL('./wallet-model-probe-2026-11-06/run.json',import.meta.url))));
validateExperienceRows(prep.records,prep.records[0].record.workspace);
assert.deepEqual(prep.independentCatalogReadback,prep.records);
assert.ok(prep.records.every(row=>row.record.source==='replay'&&row.record.schemaHash===toolSchemaHash(catalog)));
assert.deepEqual(catalog._meta['recall/verifiedExperience'],prep.records);
for(const [name,expected] of Object.entries(freeze.planSha256))assert.equal(hash(readFileSync(new URL(name,folder))),expected);
const [control,memory]=run.arms;
assert.equal(control.condition,'no-memory');assert.equal(memory.condition,'restored-memory');
assert.equal(control.trace.find(t=>t.kind==='user').text,memory.trace.find(t=>t.kind==='user').text);
assert.equal(control.summary.reason,'TOOL_ERROR');assert.equal(memory.summary.status,'COMPLETED');
assert.equal(control.summary.model,memory.summary.model);assert.equal(memory.summary.model,'gpt-5.6-luna');
assert.equal(control.summary.turnsStarted+memory.summary.turnsStarted,3);
assert.ok(run.arms.every(a=>a.summary.preflight.balance==='0'&&a.summary.preflight.hasCredits===false));
assert.equal(control.finalLocalExperience.length,1);assert.deepEqual(memory.finalLocalExperience,prep.records);
const firstA=assessFirstLookup(control.trace,catalog.inputSchema),firstB=assessFirstLookup(memory.trace,catalog.inputSchema);
const comparison=assessMemoryPair(firstA,firstB);
assert.equal(comparison,'NARROW_FIRST_CHOICE_DIFFERENCE');
assert.equal(firstA.limit,100);assert.equal(firstB.limit,10);
const exported=memory.trace.find(t=>t.kind==='tool'&&t.tool==='export_report');
const payload=JSON.parse(exported.result.content[0].text);
const reply=memory.trace.findLast(t=>t.kind==='model'&&t.phase==='final_answer').text;
assert.equal(artifactReferenceMatches(payload.artifact,reply),true);
const bytes=readFileSync(new URL('original.csv',folder));
assert.equal(hash(bytes),payload.artifact.sha256);assert.equal(bytes.length,payload.artifact.bytes);
assert.equal(bytes.toString('utf8'),payload.csv);assert.ok(payload.csv.includes('"replay"'));
const sourceError=control.trace.find(t=>t.kind==='tool'&&t.status==='failed');
assert.equal(sourceError.result._meta['recall/observation'].id,control.finalLocalExperience[0].id);
assert.ok(run.limitations.length>=5);
console.log(JSON.stringify({comparison,control:firstA,memory:firstB,originalCsv:'EXACT_BYTES_REFERENCE_AND_HASH',providerCalls:0,limits:'One fixed-order pair; local historical memory; no general improvement claim'},null,2));
