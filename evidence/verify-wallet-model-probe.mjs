import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {exactCsvDelivery,nativeToolFailed} from '../app/agent-probe-results.mjs';
import {loadOfflineActivity} from '../app/agent-activity-index.ts';
import {report,csv} from '../app/activity.ts';
const run=JSON.parse(readFileSync(new URL('./wallet-model-probe-2026-11-06/run.json',import.meta.url),'utf8'));
assert.equal(run.evaluationStatus,'FAILED');assert.equal(run.tatumCalls,0);assert.equal(run.walrusCalls,0);assert.equal(run.additionalSpendUSD,0);
assert.equal(run.localExperienceRecords,0);
assert.equal(run.attempts.flatMap(a=>a.trace).filter(t=>t.kind==='user').length,run.userTurnsStarted);assert.equal(run.userTurnsStarted,4);
const [first,luna]=run.attempts;assert.equal(first.summary.status,'STOPPED');
assert.ok(first.trace.some(t=>t.kind==='server-error'&&t.error.message.includes('model_not_found')));
assert.equal(luna.summary.model,'gpt-5.6-luna');assert.equal(luna.summary.turns.length,3);
const tools=luna.trace.filter(t=>t.kind==='tool');
const failures=tools.filter(t=>nativeToolFailed({...t,type:'mcpToolCall'}));
assert.equal(failures.length,2);assert.ok(failures.every(t=>t.tool==='find_wallet_activity'&&t.arguments.limit===100));
const decode=t=>JSON.parse(t.result.content.find(c=>c.type==='text').text);
const lookups=tools.filter(t=>t.tool==='find_wallet_activity'&&t.status==='completed').map(decode);
assert.ok(lookups.some(r=>r.transactions.length===2));assert.ok(lookups.some(r=>r.transactions.length===0));
assert.ok(lookups.every(r=>r.sourceMode==='saved-mainnet-replay'&&r.coverage.walletHistoryComplete===false&&r.coverage.freshProviderRead===false));
const gas=tools.filter(t=>t.tool==='verify_gas_payer').map(decode);assert.equal(gas.length,2);assert.ok(gas.every(r=>r.verdict==='pass'&&r.memory===null));
const exported=decode(tools.find(t=>t.tool==='export_report'));
const modelCsv=luna.trace.find(t=>t.kind==='model'&&t.phase==='final_answer'&&t.text.includes('```csv')).text;
assert.equal(exactCsvDelivery(exported.csv,modelCsv),false);
const index=loadOfflineActivity('saved');const tx=await index.transactions('mainnet',exported.report.digests);
assert.equal(exported.csv,csv(report(tx,exported.report.wallet,[],exported.report.asOf)));
assert.ok(exported.csv.includes('"replay"'));assert.equal(modelCsv.includes('replay'),false);
console.log('Negative wallet probe evidence verified offline: repeated schema failures, missing capture, rewritten CSV, and retained model-access failure. Not an acceptance pass.');
